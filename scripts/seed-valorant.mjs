async function seed() {
  console.log(`Seeding ${tips.length} Valorant tips...`)
  let ok = 0
  for (const tip of tips) {
    const res = await fetch(`${BASE}/api/valorant`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(tip),
    })
    if (res.ok) { ok++; process.stdout.write('.') }
    else { console.error(`\nFailed: ${tip.title} — ${res.status}`) }
  }
  console.log(`\nDone! ${ok}/${tips.length} tips inserted.`)
}

seed()
